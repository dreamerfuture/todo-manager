// ============================================================
// 应用入口文件（项目启动后第一个执行的 JS）
// 作用：创建一个 Vue 应用实例，挂载到 index.html 的 #app 上。
// ============================================================
import { createApp } from 'vue'      // 从 vue 包导入"创建应用"的函数
import App from './App.vue'          // 导入根组件（最外层的组件）
import './style.css'                 // 导入全局样式（对所有页面生效）

createApp(App).mount('#app')
// 上面一行 = 创建应用(用 App 组件) 然后挂载到 index.html 里
// id="app" 的 div 上。之后整个界面都由 Vue 动态生成。
